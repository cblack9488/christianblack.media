  /* About has been folded into the landing page: the biography lives there
     now, so the rail no longer lists it and about.html forwards to home. */
  /* The media kit is reachable from the landing page and the footer, but it
     is not in the rail: it is for a particular reader, not a section of the
     site. */
  /* A page that has not been written yet should not be advertised. The media
     kit is scaffolding until there is something in it, and a brand following
     a link to an empty page is worse served than one who never saw the link.
     The same test decides whether the build indexes it. */
  CB.kitReady = function () {
    var k = (CB.content || {}).mediakit || {};
    function any(list, key) {
      return (list || []).some(function (x) { return x && String(x[key] || '').trim(); });
    }
    return !!(String(k.bio || '').trim() || String(k.audience || '').trim() ||
      any(k.reach, 'value') || any(k.services, 'name') ||
      any(k.partners, 'name') || any(k.downloads, 'label'));
  };

  CB.OFF_RAIL = [
    { id: 'home', label: 'Home', href: 'index.html' },
    { id: 'mediakit', label: 'Media kit', href: 'mediakit.html' }
  ];

  CB.hrefFor = function (id) {
    var all = CB.PAGES.concat(CB.OFF_RAIL);
    for (var i = 0; i < all.length; i++) if (all[i].id === id) return all[i].href;
    return 'index.html';
  };
  /* Every journal entry has its own page under words/, generated by
     tools/build.js. The ?entry= form still works for anything that
     linked to the old URLs. */
  CB.entryHref = function (id) { return 'words/' + id + '.html'; };

  CB.numFor = function (id) {
    for (var i = 0; i < CB.PAGES.length; i++) if (CB.PAGES[i].id === id) return '0' + (i + 1);
    return '';
  };

  CB.content = window.CB_CONTENT || {};
  CB.page = document.body.getAttribute('data-page');

  /* ---------- tiny helpers ---------- */

  function el(tag, attrs, kids) {
    var n = document.createElement(tag);
    if (attrs) {
      Object.keys(attrs).forEach(function (k) {
        var v = attrs[k];
        if (v === null || v === undefined || v === false) return;
        if (k === 'text') n.textContent = v;
        else if (k === 'html') n.innerHTML = v;
        else if (k === 'class') n.className = v;
        else n.setAttribute(k, v);
      });
    }
    (kids || []).forEach(function (c) { if (c) n.appendChild(c); });
    return n;
  }
  CB.el = el;

  function frag(kids) {
    var f = document.createDocumentFragment();
    (kids || []).forEach(function (c) { if (c) f.appendChild(c); });
    return f;
  }

  /* Images dropped in Studio live in memory until export; resolve those first. */
  CB.pendingImages = CB.pendingImages || {};
  CB.resolveSrc = function (src) {
    if (!src) return '';
    var p = CB.pendingImages[src];
    return p ? p.url : src;
  };

  CB.fmtDate = function (iso) {
    if (!iso) return '';
    var d = new Date(iso + (iso.length === 10 ? 'T12:00:00' : ''));
    if (isNaN(d)) return iso;
    var m = ['January', 'February', 'March', 'April', 'May', 'June', 'July',
             'August', 'September', 'October', 'November', 'December'];
    return m[d.getMonth()] + ' ' + d.getDate() + ', ' + d.getFullYear();
  };

  /* Alt text. Most photographs here carry a caption, credit or label
     worth describing; an empty alt tells a screen reader to skip the
     image entirely, which is wrong for a photo-led site. An explicit
     `alt` in content.js always wins, including an explicit empty one. */
  function creditPhrase(c) {
    if (!c) return '';
    return String(c).replace(/^Photo\s*[\u00b7:]\s*/i, 'photograph by ');
  }
  CB.altFor = function (item, fallback) {
    item = item || {};
    if (item.alt !== undefined && item.alt !== null) return item.alt;
    return [fallback, creditPhrase(item.credit)].filter(Boolean).join(' \u2014 ');
  };

